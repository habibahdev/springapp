-- V1 : création des tables

create table category (
  id bigint generated by default as identity primary key,
  name varchar(255) not null,
  constraint uk_category_name unique (name)
);

create table users (
   id bigint generated by default as identity primary key,
   email varchar(255) not null,
   full_name varchar(255) not null,
   password varchar(255) not null,
   role varchar(255) not null,
   constraint uk_users_email unique (email),
   constraint ck_users_role check ( role in ('USER', 'ADMIN') )
);

create table product (
     id bigint generated by default as identity primary key,
     name varchar(255) not null,
     description varchar(2000),
     price numeric(10,2) not null,
     stock integer not null,
     image_url varchar(255),
     category_id bigint,
     constraint fk_product_category foreign key (category_id) references category (id)
);

create table purchase (
      id bigint generated by default as identity primary key,
      customer_name varchar(255),
      customer_email varchar(255),
      shipping_address varchar(255),
      status varchar(255),
      created_at timestamp(6),
      total numeric(10,2),
      user_id bigint,
      constraint fk_purchase_user foreign key (user_id) references users(id),
      constraint ck_purchase_status check ( status in ('PENDING', 'PAID', 'SHIPPED', 'CANCELLED') )
);

create table detail (
    id bigint generated by default as identity primary key,
    quantity integer not null,
    unit_price numeric(10,2),
    purchase_id bigint not null,
    product_id bigint not null,
    constraint fk_detail_purchase foreign key (purchase_id) references purchase (id),
    constraint fk_detail_product foreign key (product_id) references product (id)
);

create index idx_product_category on product (category_id);
create index idx_purchase_user on purchase (user_id);
create index idx_detail_purchase on detail (purchase_id);
create index idx_detail_product on detail (product_id);